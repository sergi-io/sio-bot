#!/usr/bin/env bun
/**
 * Prebuild script that embeds static assets into TypeScript files
 * so they're included in the compiled binary.
 */

import fs from 'fs';
import path from 'path';

const JOURNAL_TEMPLATES_DIR = path.resolve(import.meta.dir, '../src/journal/templates');
const JOURNAL_OUTPUT_FILE = path.resolve(import.meta.dir, '../src/journal/templates.ts');
const FRONTEND_DIR = path.resolve(import.meta.dir, '../frontend');
const FRONTEND_OUTPUT_FILE = path.resolve(import.meta.dir, '../src/comms/commandCenterFrontend.ts');

function escapeTemplateString(content: string): string {
  // Escape backticks and ${} to prevent template literal issues
  return content
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

function generateJournalTemplatesFile(): void {
  const stylesContent = fs.readFileSync(path.join(JOURNAL_TEMPLATES_DIR, 'styles.css'), 'utf-8');
  const appContent = fs.readFileSync(path.join(JOURNAL_TEMPLATES_DIR, 'app.js'), 'utf-8');
  const htmlContent = fs.readFileSync(path.join(JOURNAL_TEMPLATES_DIR, 'index.html'), 'utf-8');

  const output = `// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-journal-templates.ts
// Edit the source files in src/journal/templates/ instead

export const stylesTemplate = \`${escapeTemplateString(stylesContent)}\`;

export const appTemplate = \`${escapeTemplateString(appContent)}\`;

export const htmlTemplate = \`${escapeTemplateString(htmlContent)}\`;
`;

  fs.writeFileSync(JOURNAL_OUTPUT_FILE, output, 'utf-8');
  console.log('Generated src/journal/templates.ts from static files');
}

async function generateCommandCenterFrontendFile(): Promise<void> {
  const build = await Bun.build({
    entrypoints: [path.join(FRONTEND_DIR, 'src/main.tsx')],
    minify: false,
    target: 'browser',
  });

  if (!build.success || build.outputs.length === 0) {
    const errors = build.logs.map((item) => item.message).join('\n');
    throw new Error(`Unable to build embedded command center frontend:\n${errors}`);
  }

  const appJsContent = await build.outputs[0]!.text();
  const stylesContent = fs.readFileSync(path.join(FRONTEND_DIR, 'styles.css'), 'utf-8');
  const htmlContent = fs.readFileSync(path.join(FRONTEND_DIR, 'index.html'), 'utf-8');

  const output = `/* eslint-disable no-irregular-whitespace */
// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-journal-templates.ts
// Edit the source files in frontend/ instead

export const commandCenterAppJs = \`${escapeTemplateString(appJsContent)}\`;

export const commandCenterStylesCss = \`${escapeTemplateString(stylesContent)}\`;

export const commandCenterIndexHtml = \`${escapeTemplateString(htmlContent)}\`;
`;

  fs.writeFileSync(FRONTEND_OUTPUT_FILE, output, 'utf-8');
  console.log('Generated src/comms/commandCenterFrontend.ts from frontend assets');
}

async function main(): Promise<void> {
  generateJournalTemplatesFile();
  await generateCommandCenterFrontendFile();
}

await main();
